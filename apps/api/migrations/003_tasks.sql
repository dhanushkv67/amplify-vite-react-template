CREATE TABLE IF NOT EXISTS tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'in_progress', 'done')),
  assignee_id bigint REFERENCES users(id) ON DELETE SET NULL,
  due_date date,
  created_by bigint NOT NULL REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tasks_title_nonblank CHECK (length(btrim(title)) > 0)
);
CREATE INDEX IF NOT EXISTS tasks_project_status_id_idx ON tasks (project_id, status, id);
CREATE INDEX IF NOT EXISTS tasks_project_assignee_idx ON tasks (project_id, assignee_id);
